r"""
test_show_shred.py — демонстрация работы ШРЕДДЕРА по шагам.

Показывает, что физически происходит с файлом:
  1. До обработки — читаемый текст.
  2. После перезаписи нулями — байты 00 00 00 00...
  3. После обрезки до 32 байт — 32 случайных байта.
  4. После удаления — файла нет.

НЕ трогает боевой engine.py — работает со своим тестовым файлом.
"""

import os


TEST_FILE = "_shredder_demo.txt"
TEST_CONTENT = (
    "ЭТО СЕКРЕТНЫЙ ТЕКСТ ДЛЯ ПРОВЕРКИ ШРЕДДЕРА.\n"
    "Тут много текста, чтобы было видно структуру.\n"
    "1234567890 ABCDEFGHIJKLMNOPQRSTUVWXYZ\n"
    "Строка два. Строка три. Пароль123.\n"
)


def show_hex(path: str, n: int = 96):
    r"""
    Печатает первые n байт файла в hex-формате.
    Слева — смещение, в середине — байты в hex, справа — ASCII.
    Нечитаемые байты заменяются точкой.
    """
    with open(path, 'rb') as f:
        data = f.read(n)

    print(f"  Первые {len(data)} байт (hex + ascii):")
    for i in range(0, len(data), 16):
        chunk = data[i:i + 16]
        hex_part = ' '.join(f'{b:02x}' for b in chunk)
        ascii_part = ''.join(chr(b) if 32 <= b < 127 else '.' for b in chunk)
        print(f"  {i:08x}  {hex_part:<48}  {ascii_part}")


def pause(msg: str):
    """Пауза — ждём Enter от пользователя."""
    print()
    input(f">>> {msg}\n    Нажми Enter, чтобы продолжить...")


# ---------- ПОДГОТОВКА ----------
# Если файл остался от прошлого прогона — удаляем.
if os.path.exists(TEST_FILE):
    os.remove(TEST_FILE)


# ============================================================
#  ШАГ 1. СОЗДАЁМ ФАЙЛ
# ============================================================
print("=" * 68)
print("ШАГ 1. Создаю тестовый файл с секретным текстом.")
print("=" * 68)

with open(TEST_FILE, 'w', encoding='utf-8') as f:
    f.write(TEST_CONTENT)

size = os.path.getsize(TEST_FILE)
print(f"Файл:   {os.path.abspath(TEST_FILE)}")
print(f"Размер: {size} байт")
print()
print(f"Читаемый текст (первые 60 символов):")
print(f'  "{TEST_CONTENT[:60]}"')
print()
print("То же самое в hex — видишь русские буквы? Это UTF-8, поэтому")
print("одна буква = 2 байта.")
print()
show_hex(TEST_FILE)

pause("Открой файл в Проводнике, убедись что там текст.")


# ============================================================
#  ШАГ 2. ПЕРЕЗАПИСЬ НУЛЯМИ
# ============================================================
print()
print("=" * 68)
print("ШАГ 2. Перезаписываю содержимое нулями (режим 'r+b').")
print("=" * 68)

# Открываем 'r+b' — читать и писать БЕЗ усечения.
# Размер файла не меняется — Windows пишет поверх тех же секторов.
with open(TEST_FILE, 'r+b') as f:
    f.seek(0)
    f.write(b'\x00' * size)          # пишем нули по всему файлу
    f.flush()
    os.fsync(f.fileno())             # заставляем Windows сбросить буферы на диск

print(f"Размер после перезаписи: {os.path.getsize(TEST_FILE)} байт")
print("(размер НЕ изменился — данные легли поверх старых)")
print()
show_hex(TEST_FILE)

print()
print("Что видно: сплошные 00 00 00 00 — это и есть нули.")
print("Текста больше нет. Именно это делает ПОЛНЫЙ режим.")
print("Заметь: файл всё ещё существует, размер тот же,")
print("но внутри — пустота. Recuva тут уже ничего не восстановит.")

pause("Посмотри результат.")


# ============================================================
#  ШАГ 3. ОБРЕЗКА ДО 32 БАЙТ + СЛУЧАЙНЫЕ БАЙТЫ
# ============================================================
print()
print("=" * 68)
print("ШАГ 3. Обрезаю файл до 32 байт, заполняю случайными байтами.")
print("=" * 68)

with open(TEST_FILE, 'r+b') as f:
    f.truncate(32)                   # обрезаем до 32 байт
    f.seek(0)                        # страховка: указатель в начало
    f.write(os.urandom(32))          # 32 случайных байта
    f.flush()
    os.fsync(f.fileno())

print(f"Размер после обрезки: {os.path.getsize(TEST_FILE)} байт")
print()
show_hex(TEST_FILE)

print()
print("Что видно: случайные байты, никакой структуры.")
print("Даже если бы кто-то нашёл огрызок — он бесполезен.")
print("Именно так выглядит файл за секунду до удаления.")

pause("Посмотри результат.")


# ============================================================
#  ШАГ 4. УДАЛЕНИЕ
# ============================================================
print()
print("=" * 68)
print("ШАГ 4. Удаляю файл мимо корзины.")
print("=" * 68)

os.remove(TEST_FILE)

if os.path.exists(TEST_FILE):
    print("ОШИБКА: файл всё ещё существует!")
else:
    print("✅ Файл удалён.")
    print()
    print("Проверь Проводник — файла нет.")
    print("Проверь Корзину — там его тоже нет (мы удаляем мимо корзины).")
    print()
    print("Теперь можешь запустить Recuva на этой папке и убедиться,")
    print("что восстановить нечего — только нули в освободившемся месте.")

print()
print("=" * 68)
print("ГОТОВО.")
print("=" * 68)